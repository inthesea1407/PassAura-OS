//! Conformance vectors for allowlist v2, generated from the real code with
//! fixed test keys. Committed file: tests/vectors/allowlist_v2.json.
//! Regenerate with: UPDATE_VECTORS=1 cargo test -p pos-gate --test conformance_v2
//! The test keys are public test values and protect nothing.

use ed25519_dalek::{Signer, SigningKey};
use pos_gate::allowlist_v2::*;
use serde_json::{json, Value};

const NOW: i64 = 1_000_100;

fn key() -> SigningKey {
    SigningKey::from_bytes(&[7u8; 32])
}

fn other_key() -> SigningKey {
    SigningKey::from_bytes(&[9u8; 32])
}

fn doc(sk: &SigningKey, seq: u64) -> V2Allowlist {
    let pk = hex::encode(sk.verifying_key().to_bytes());
    let id = derive_key_id(&pk);
    V2Allowlist {
        format: "passaura-allowlist".into(),
        version: 2,
        sequence: seq,
        issued_at: 1_000_000,
        expires_at: 1_086_400,
        signed_by: id.clone(),
        keyring: V2Keyring {
            keys: vec![V2Key { key_id: id, public_key_hex: pk, valid_from: 0, valid_until: 2_000_000, retired: false }],
        },
        entries: vec![V2Entry { name: "ripgrep".into(), version: Some("14.1.0".into()), sha256: "a".repeat(64) }],
        signature_hex: String::new(),
    }
}

fn sign(mut d: V2Allowlist, sk: &SigningKey) -> V2Allowlist {
    d.signature_hex = hex::encode(sk.sign(&canonical_payload_bytes(&d).unwrap()).to_bytes());
    d
}

fn case(name: &str, d: &V2Allowlist, now: i64, stored: Option<(u64, String)>) -> Value {
    let r = verify_v2(d, now, stored.as_ref().map(|(s, h)| (*s, h.as_str())));
    json!({
        "name": name,
        "now": now,
        "stored": stored.map(|(s, h)| json!({"sequence": s, "digest_hex": h})),
        "document": d,
        "expect": match r { Ok(()) => "ok".to_string(), Err(e) => format!("{:?}", e).split(|c| c == '(' || c == ' ').next().unwrap().to_string() },
    })
}

fn build() -> Value {
    let sk = key();
    let good = sign(doc(&sk, 5), &sk);
    let digest = canonical_digest_hex(&good).unwrap();
    let mut cases = vec![];
    cases.push(case("valid", &good, NOW, None));
    cases.push(case("valid_same_sequence_same_digest", &good, NOW, Some((5, digest.clone()))));
    cases.push(case("valid_higher_sequence", &good, NOW, Some((4, "00".repeat(32)))));
    cases.push(case("downgrade_lower_sequence", &good, NOW, Some((6, digest.clone()))));
    cases.push(case("same_sequence_different_digest", &good, NOW, Some((5, "00".repeat(32)))));
    cases.push(case("expired", &good, 1_086_400, None));
    cases.push(case("not_yet_valid", &good, 999_999, None));
    let mut t = good.clone();
    t.entries[0].sha256 = "b".repeat(64);
    cases.push(case("tampered_entry", &t, NOW, None));
    let mut t = good.clone();
    t.sequence = 6;
    cases.push(case("tampered_sequence", &t, NOW, None));
    let mut t = good.clone();
    t.version = 3;
    cases.push(case("unsupported_version", &t, NOW, None));
    let t = sign(doc(&other_key(), 5), &other_key());
    let mut t2 = good.clone();
    t2.signature_hex = t.signature_hex.clone();
    cases.push(case("signature_from_other_key", &t2, NOW, None));
    let mut t = doc(&sk, 5);
    t.keyring.keys[0].retired = true;
    cases.push(case("signer_retired", &sign(t, &sk), NOW, None));
    let mut t = doc(&sk, 5);
    t.signed_by = "ed25519:0000000000000000".into();
    cases.push(case("signer_not_in_keyring", &sign(t, &sk), NOW, None));
    let mut t = doc(&sk, 5);
    t.keyring.keys.clear();
    cases.push(case("empty_keyring", &sign(t, &sk), NOW, None));
    let mut t = doc(&sk, 5);
    t.keyring.keys[0].valid_from = 1_050_000;
    cases.push(case("key_not_valid_at_issue_time", &sign(t, &sk), NOW, None));
    let mut t = doc(&sk, 5);
    t.expires_at = t.issued_at;
    cases.push(case("empty_validity_window", &sign(t, &sk), NOW, None));
    let mut t = doc(&sk, 5);
    t.format = "other".into();
    cases.push(case("wrong_format", &sign(t, &sk), NOW, None));
    json!({
        "description": "PassAura allowlist v2 conformance vectors. Generated by the Rust implementation; not independently verified. Test keys are public.",
        "signing_seed_hex": "07".repeat(32),
        "canonical_form": "document minus signature_hex, JSON with sorted keys, no whitespace; signature = Ed25519 over those bytes",
        "digest": "SHA-256 of the same canonical bytes, lowercase hex",
        "cases": cases,
    })
}

const PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../tests/vectors/allowlist_v2.json");

#[test]
fn vectors_match_committed_file_and_implementation() {
    let v = build();
    let text = serde_json::to_string_pretty(&v).unwrap() + "\n";
    if std::env::var("UPDATE_VECTORS").is_ok() {
        std::fs::write(PATH, &text).unwrap();
    }
    let committed = std::fs::read_to_string(PATH).expect("vector file missing; run with UPDATE_VECTORS=1");
    assert_eq!(committed, text, "vector file out of date");

    // Replay the committed file through the verifier, as a third party would.
    let parsed: Value = serde_json::from_str(&committed).unwrap();
    for c in parsed["cases"].as_array().unwrap() {
        let d: V2Allowlist = serde_json::from_value(c["document"].clone()).unwrap();
        let stored = c["stored"].as_object().map(|o| (o["sequence"].as_u64().unwrap(), o["digest_hex"].as_str().unwrap().to_string()));
        let r = verify_v2(&d, c["now"].as_i64().unwrap(), stored.as_ref().map(|(s, h)| (*s, h.as_str())));
        let got = match r { Ok(()) => "ok".to_string(), Err(e) => format!("{:?}", e).split(|ch| ch == '(' || ch == ' ').next().unwrap().to_string() };
        assert_eq!(got, c["expect"].as_str().unwrap(), "case {}", c["name"]);
    }
}

#[test]
fn expectations_are_what_the_spec_says() {
    let v = build();
    let get = |n: &str| v["cases"].as_array().unwrap().iter().find(|c| c["name"] == n).unwrap()["expect"].as_str().unwrap().to_string();
    assert_eq!(get("valid"), "ok");
    assert_eq!(get("tampered_entry"), "SignatureInvalid");
    assert_eq!(get("downgrade_lower_sequence"), "DowngradeRejected");
    assert_eq!(get("expired"), "Expired");
    assert_eq!(get("not_yet_valid"), "NotYetValid");
    assert_eq!(get("signer_retired"), "SignedByRetired");
    assert_eq!(get("signature_from_other_key"), "SignatureInvalid");
    assert_eq!(get("same_sequence_different_digest"), "DigestMismatch");
}
